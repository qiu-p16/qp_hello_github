-- #############################################################################
-- #  学生成绩管理系统 —— 数据库设计与代码（score_db）
-- #  负责人：林嘉辉（数据库部分）
-- #  环境：MySQL 8.0 / 9.x ｜ 字符集 utf8mb4 ｜ 存储引擎 InnoDB
-- #  用法：在 DataGrip / Navicat / mysql 命令行中整段执行即可
-- #
-- #  ============================== 设计说明 ==============================
-- #  一、四张表：student 学生表 ｜ course 课程表 ｜ score 成绩表 ｜ user 用户表
-- #  二、表关系：student 与 course 为“多对多”，通过 score 连接表拆成两个“一对多”。
-- #          student 1 ──< N score N >── 1 course
-- #  三、完整性约束：主键、外键、唯一、联合唯一(student_id,course_id)、
-- #      检查(成绩0~100)、非空 / 默认值 / 枚举。
-- #  四、规范化：满足第三范式，姓名/班级/课程名通过 JOIN 获取，不冗余。
-- #  五、安全：密码不存明文，使用 djb2 哈希（123456 → 000006527dd1705a）。
-- #  六、数据规模：80 名学生（25级区块链班40 + 数智应用班40）、
-- #      8 门课程、640 条成绩、8 个账号。
-- #      代表性成绩手工录入，其余成绩用 CROSS JOIN 批量生成；
-- #      两个班使用不同公式，避免数据雷同。
-- #  #############################################################################


-- #############################################################################
-- # 一、创建数据库
-- #############################################################################
DROP DATABASE IF EXISTS score_db;
CREATE DATABASE score_db DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE score_db;


-- #############################################################################
-- # 二、学生信息表 student
-- #############################################################################
CREATE TABLE student (
    id          INT PRIMARY KEY AUTO_INCREMENT COMMENT '主键',
    student_id  VARCHAR(20) NOT NULL UNIQUE    COMMENT '学号(唯一)',
    name        VARCHAR(50) NOT NULL           COMMENT '姓名',
    class_name  VARCHAR(50) NOT NULL           COMMENT '班级',
    gender      CHAR(2)     DEFAULT '男'       COMMENT '性别',
    age         INT         DEFAULT 18         COMMENT '年龄'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='学生信息表';


-- #############################################################################
-- # 三、课程信息表 course
-- #############################################################################
CREATE TABLE course (
    id          INT PRIMARY KEY AUTO_INCREMENT,
    course_id   VARCHAR(20)  NOT NULL UNIQUE    COMMENT '课程号(唯一)',
    course_name VARCHAR(100) NOT NULL           COMMENT '课程名',
    credit      FLOAT        NOT NULL DEFAULT 2.0 COMMENT '学分',
    semester    VARCHAR(20)  NOT NULL           COMMENT '开课学期,如2025-1'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='课程信息表';


-- #############################################################################
-- # 四、成绩表 score（核心关系表）
-- #############################################################################
CREATE TABLE score (
    id          INT PRIMARY KEY AUTO_INCREMENT,
    student_id  VARCHAR(20) NOT NULL,
    course_id   VARCHAR(20) NOT NULL,
    score       FLOAT       NOT NULL,
    semester    VARCHAR(20),
    CONSTRAINT fk_score_stu FOREIGN KEY (student_id) REFERENCES student(student_id),
    CONSTRAINT fk_score_cou FOREIGN KEY (course_id)  REFERENCES course(course_id),
    UNIQUE KEY uk_stu_course (student_id, course_id),
    CONSTRAINT ck_score_range CHECK (score BETWEEN 0 AND 100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='成绩表';


-- #############################################################################
-- # 五、用户表 user
-- #    123456 的 djb2 哈希 = 000006527dd1705a
-- #############################################################################
CREATE TABLE user (
    id         INT PRIMARY KEY AUTO_INCREMENT,
    username   VARCHAR(50) NOT NULL UNIQUE       COMMENT '登录名',
    password   VARCHAR(255) NOT NULL             COMMENT 'djb2哈希密码',
    role       ENUM('admin','teacher','student') NOT NULL COMMENT '角色',
    student_id VARCHAR(20) NULL                  COMMENT '学生角色关联学号'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户表';


