-- # 九、补齐区块链班成绩（原公式，限定班级）
-- #############################################################################
INSERT INTO score(student_id, course_id, score, semester)
SELECT s.student_id, c.course_id,
       GREATEST(40, LEAST(100,
           60 + MOD(s.id * 37, 30) + MOD(s.id * 7 + c.id * 13, 15) - 7
       )),
       c.semester
FROM student s
CROSS JOIN course c
WHERE s.class_name = '25级区块链班'
  AND NOT EXISTS (
      SELECT 1 FROM score sc
      WHERE sc.student_id = s.student_id AND sc.course_id = c.course_id
  );


