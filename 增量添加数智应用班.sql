-- 2) 为数智班学生生成全部 8 门课程成绩（新公式，限定班级；NOT EXISTS 防重复）
--    base = 58 + MOD(id*29,33)，课程调整 MOD(id*11+course_id*17,15)-7，限制在 40~100
INSERT INTO score(student_id, course_id, score, semester)
SELECT s.student_id, c.course_id,
       GREATEST(40, LEAST(100,
           58 + MOD(s.id * 29, 33) + MOD(s.id * 11 + c.id * 17, 15) - 7
       )),
       c.semester
FROM student s
CROSS JOIN course c
WHERE s.class_name = '数智应用班'
  AND NOT EXISTS (
      SELECT 1 FROM score sc
      WHERE sc.student_id = s.student_id AND sc.course_id = c.course_id
  );

